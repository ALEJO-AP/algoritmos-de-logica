package EjerciciosCesde;

public class ejemploCicloMientrasAcumulador {
    public static void main(String[] args) {
        
        int  inicio, suma;

        inicio = 1;
        suma = 0;

        while (inicio <= 10) {

            System.out.println(suma = suma + inicio);

            inicio = inicio + 1;
        }
    }
}
